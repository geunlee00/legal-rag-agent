"""적용법령 진단 (A: 규칙 기반).

회사 프로필(CompanyProfile)을 받아 '적용되는 법령 목록'을 만든다.

핵심 아이디어:
    - 프로필의 각 항목(체크박스)이 하나의 조건이 된다.
    - 조건이 참이면 해당 법령을 결과에 담는다.
    - 결과에는 '왜 적용되는지(reason)'도 함께 담아 설명 가능하게 한다.

왜 규칙 기반인가:
    - 정확하고(추측 없음) 설명 가능하다. 컴플라이언스는 이 두 가지가 생명.
    - 나중에 C(근거보강)에서 여기 나온 법령을 RAG로 검색해 실제 조문을 붙인다.

결과 형태(예):
    [
        {"law": "개인정보 보호법", "reason": "개인정보를 취급하는 사업자는 ..."},
        {"law": "전자상거래법",   "reason": "온라인 판매를 하는 사업자는 ..."},
    ]
"""


def diagnose(profile):
    """CompanyProfile 하나를 받아 적용 법령 목록(list[dict])을 돌려준다."""
    results = []

    # ── 규칙 1 (완성 예시) : 개인정보 취급 → 개인정보 보호법 ─────────────
    # 이게 '한 규칙'의 기본 모양이다. 조건(if) → results.append(...).
    if profile.handles_personal_data:
        results.append({
            "law": "개인정보 보호법",
            "reason": "개인정보를 취급하는 사업자는 개인정보 보호법의 적용을 받습니다.",
        })

    # ── 규칙 2 : 민감정보(건강 등) 취급 → 개인정보 보호법(민감정보) ──────
    # 민감정보(건강·유전·범죄경력 등)는 원칙적으로 처리 금지이고,
    # 별도 동의 등 요건을 갖춰야만 처리할 수 있어 더 엄격하다.
    if profile.handles_sensitive_data:
        results.append({
            "law": "개인정보 보호법 (민감정보)",
            "reason": "건강 등 민감정보를 처리하려면 별도 동의 등 강화된 요건을 갖춰야 합니다.",
        })

    # ── 규칙 3 : 위치정보 취급 → 위치정보법 ───────────────────────────
    if profile.handles_location_data:
        results.append({
            "law": "위치정보의 보호 및 이용 등에 관한 법률",
            "reason": "개인의 위치정보를 수집·이용하는 사업자는 위치정보법의 적용을 받습니다.",
        })

    # ── 규칙 4 : 신용/결제정보 취급 → 신용정보법 ──────────────────────
    if profile.handles_financial_data:
        results.append({
            "law": "신용정보의 이용 및 보호에 관한 법률",
            "reason": "신용·결제 등 금융 관련 개인정보를 다루면 신용정보법의 적용을 받습니다.",
        })

    # ── 규칙 5 : 만 14세 미만 정보 취급 → 개인정보 보호법(법정대리인) ───
    # 아동의 개인정보는 법정대리인(보호자)의 동의를 받아야 한다.
    if profile.handles_minor_data:
        results.append({
            "law": "개인정보 보호법 (법정대리인 동의)",
            "reason": "만 14세 미만 아동의 개인정보는 법정대리인의 동의를 받아야 처리할 수 있습니다.",
        })

    # ── 규칙 6 : 온라인 판매 → 전자상거래법 ───────────────────────────
    if profile.does_online_sales:
        results.append({
            "law": "전자상거래 등에서의 소비자보호에 관한 법률",
            "reason": "온라인으로 재화·서비스를 판매하는 사업자는 전자상거래법상 소비자보호 의무를 집니다.",
        })

    # ── 규칙 7 : 광고성 정보 전송 → 정보통신망법 ──────────────────────
    # 이메일·문자 등 광고성 정보는 사전 수신동의(옵트인)가 필요하다.
    if profile.does_marketing:
        results.append({
            "law": "정보통신망 이용촉진 및 정보보호 등에 관한 법률",
            "reason": "이메일·문자 등 광고성 정보를 전송하려면 수신자의 사전 동의가 필요합니다.",
        })

    # ── 규칙 8 : 개인정보 국외 이전 → 개인정보 보호법(국외이전) ─────────
    if profile.overseas_transfer:
        results.append({
            "law": "개인정보 보호법 (국외 이전)",
            "reason": "개인정보를 국외로 이전하려면 정보주체 고지·동의 등 국외이전 요건을 지켜야 합니다.",
        })

    return results
